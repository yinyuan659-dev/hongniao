/** 最后一段：现在聊到哪了、这一轮该怎么做 */
export function directive(o: { topic: number; turns: number; skip: boolean; forceNext: boolean; extraTurns: number }) {
  return `${progress(o)}\n按规定的格式只输出一个 JSON 对象：{"reply": "…", "quick": ["…"], "topic": 0, "done": false, "flag": ""}`;
}

function progress(o: { topic: number; turns: number; skip: boolean; forceNext: boolean; extraTurns: number }) {
  const { topic, turns } = o;
  const skip = o.skip ? '用户不想回答刚才的问题，不要追问，换一个。' : '';
  // 六个话题聊完后的自由补充
  if (topic >= TOPICS.length) {
    if (o.extraTurns >= MAX_EXTRA_TURNS) return `【当前进度】补充得差不多了。${skip}请用一两句话温暖地收尾，告诉用户你这就去更新画像；done 填 true，quick 给空数组。`;
    return `【当前进度】六个话题已经聊过一遍，现在是自由补充。${skip}顺着用户的话回应，可以追问一句；topic 填最接近的话题编号。`;
  }
  const cur = `正在聊话题 ${topic}「${TOPICS[topic].name}」，这个话题用户已经回答了 ${turns} 轮。`;
  const last = topic === TOPICS.length - 1;
  // 每个话题至少聊够 MIN_TURNS_PER_TOPIC 轮，不然一个话题一句话就过去了，了解不到什么
  if (!o.forceNext && turns < MIN_TURNS_PER_TOPIC) {
    return `【当前进度】${cur}${o.skip ? '用户不想回答刚才的问题，不要追问，换一个这个话题里别的问题。' : '先不要换话题，顺着用户的回答在这个话题里再问一个更具体的问题。'}topic 填 ${topic}。`;
  }
  if (o.forceNext || turns >= MAX_TURNS_PER_TOPIC) {
    if (last) return `【当前进度】${cur}${skip}六个话题都聊完了。请用一两句话温暖地收尾，告诉用户你这就去整理画像；done 填 true，quick 给空数组，不要再提问。`;
    return `【当前进度】${cur}${skip}这个话题到此为止。请用一句话接住用户的话，然后换到话题 ${topic + 1}「${TOPICS[topic + 1].name}」问第一个问题，topic 填 ${topic + 1}。`;
  }
  if (last) return `【当前进度】${cur}${skip}这是最后一个话题。了解得差不多了就收尾（done 填 true，不再提问）；否则继续追问，topic 填 ${topic}。`;
  return `【当前进度】${cur}${skip}了解得差不多了就过渡到话题 ${topic + 1}「${TOPICS[topic + 1].name}」（topic 填 ${topic + 1}）；否则继续追问（topic 填 ${topic}）。`;
}

